    /** Local grouping by Conventional Commit type (also the fallback without AI). */
    P.groupCommits = function (text) {
        const g = { Added: [], Fixed: [], Changed: [], Performance: [], Docs: [], Other: [] };
        String(text || '').split('\n').map(l => l.trim()).filter(Boolean).forEach(l => {
            const msg = l.replace(/^[0-9a-f]{7,40}\s+/, '');
            if (/^merge\b/i.test(msg)) return;
            const m = /^(\w+)(\([^)]*\))?!?:\s*(.+)/.exec(msg);
            const t = m ? m[1].toLowerCase() : '';
            const body = m ? (m[2] ? `**${m[2].slice(1, -1)}:** ` : '') + m[3] : msg;
            (t === 'feat' ? g.Added : t === 'fix' ? g.Fixed : t === 'perf' ? g.Performance : t === 'docs' ? g.Docs : ['refactor', 'style', 'chore', 'build', 'ci'].includes(t) ? g.Changed : g.Other).push(body);
        });
        return g;
    };
