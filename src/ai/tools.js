// ------------------------------------------------------------------ COLOUR MATH (#113)
export function hexToRgb(hex) {
    let h = String(hex || '').replace('#', '').trim();
    if (h.length === 3) h = h.split('').map(c => c + c).join('');
    if (!/^[0-9a-f]{6}$/i.test(h)) return null;
    return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));
}
export const rgbToHex = (rgb) => '#' + rgb.map(v => clamp(Math.round(v), 0, 255).toString(16).padStart(2, '0')).join('');
export function rgbToHsl([r, g, b]) {
    r /= 255; g /= 255; b /= 255;
    const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
    if (max === min) return [0, 0, l * 100];
    const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    let h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
    return [h * 60, s * 100, l * 100];
}
export function hslToHex(h, s, l) {
    h = ((h % 360) + 360) % 360; s = clamp(s, 0, 100) / 100; l = clamp(l, 0, 100) / 100;
    const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
    const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
    return rgbToHex([f(0) * 255, f(8) * 255, f(4) * 255]);
}
const lum = (hex) => { const c = hexToRgb(hex).map(v => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };
export function contrastRatio(a, b) { const x = lum(a), y = lum(b); return +((Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)).toFixed(2); }
export const SCHEMES = { complementary: [0, 180], analogous: [0, 30, -30], triadic: [0, 120, 240], split: [0, 150, 210], tetradic: [0, 90, 180, 270], monochrome: [0] };
/** Harmonious palette + light/dark theme variables with WCAG-checked text colours. */
export function generatePalette(base, scheme = 'analogous') {
    const rgb = hexToRgb(base);
    if (!rgb) return null;
    const [h, s, l] = rgbToHsl(rgb);
    const offs = SCHEMES[scheme] || SCHEMES.analogous;
    const colors = offs.map(o => hslToHex(h + o, s, l));
    if (scheme === 'monochrome') colors.push(hslToHex(h, s, clamp(l - 20, 8, 92)), hslToHex(h, s, clamp(l + 20, 8, 92)));
    const shades = [95, 85, 70, 55, 45, 35, 25, 15].map(L => hslToHex(h, Math.min(s, 90), L));
    const textOn = (bg) => (contrastRatio(bg, '#ffffff') >= contrastRatio(bg, '#111111') ? '#ffffff' : '#111111');
    const mk = (dark) => ({
        '--color-primary': dark ? hslToHex(h, s, Math.max(l, 60)) : hslToHex(h, s, Math.min(l, 45)),
        '--color-secondary': dark ? hslToHex(h + offs[1 % offs.length], s * 0.8, 65) : hslToHex(h + offs[1 % offs.length], s * 0.8, 40),
        '--color-bg': dark ? hslToHex(h, Math.min(s, 20), 8) : hslToHex(h, Math.min(s, 30), 98),
        '--color-surface': dark ? hslToHex(h, Math.min(s, 18), 13) : '#ffffff',
        '--color-text': dark ? hslToHex(h, 10, 92) : hslToHex(h, 15, 12),
        '--color-muted': dark ? hslToHex(h, 8, 65) : hslToHex(h, 8, 40),
        '--color-border': dark ? hslToHex(h, 12, 22) : hslToHex(h, 15, 88)
    });
    const light = mk(false), dark = mk(true);
    light['--color-on-primary'] = textOn(light['--color-primary']);
    dark['--color-on-primary'] = textOn(dark['--color-primary']);
    const checks = [['light', light], ['dark', dark]].map(([n, t]) => ({ theme: n, text: contrastRatio(t['--color-text'], t['--color-bg']), primary: contrastRatio(t['--color-on-primary'], t['--color-primary']) }));
    const vars = (o) => Object.entries(o).map(([k, v]) => `  ${k}: ${v};`).join('\n');
    const css = `/* Generated by OX-Alpha — ${scheme} palette from ${base} */\n:root {\n${vars(light)}\n${shades.map((c, i) => `  --color-primary-${(i + 1) * 100}: ${c};`).join('\n')}\n}\n@media (prefers-color-scheme: dark) {\n  :root {\n${vars(dark).replace(/^/gm, '  ')}\n  }\n}\n[data-theme="dark"] {\n${vars(dark)}\n}\n`;
    return { base, scheme, colors, shades, light, dark, checks, css };
}

