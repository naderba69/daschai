    const eg = GH.state.gists.find(x => x.id === 'abc123def456');
    ok(eg.files['b.js'] && eg.files['b.js'].content === 'const b = 2;' && !eg.files['a.js'], 'gist file edited + renamed');
    await app.ghxForkGist('abc123def456');
    ok(GH.state.gists.some(x => x.id.startsWith('fa11')), 'gist forked');
    setConfirm(true);
    await app.ghxDeleteGist('abc123def456');
    ok(!GH.state.gists.some(x => x.id === 'abc123def456') && !app.ghView, 'gist deleted');
    const paths2 = await app.ghxGistToProject(GH.state.gists[0].id);
    ok(paths2.length >= 1 && app.virtualProjectFiles.has(paths2[0]), 'gist opened into the project');

    // ------------------------------------------------------------------
    section('Organizations, teams, members, roles, billing, audit (#481-#486)');
    await app.ghxLoad('org', 'orgs');
    ok(d.querySelector('[data-org="acme"]') && /مالك/.test(body().textContent), 'organizations with my role (#481)');
    await app.ghxOpenOrg('acme', 'members');
    ok(d.querySelector('[data-member="u2"]') && d.querySelector('[data-role-of="u2"]'), 'members with role selectors (#483)');
    await app.ghxOrgSetRole('acme', 'u2', 'admin');
    ok(GH.state.orgAdmins.includes('u2'), 'member promoted to owner (#484)');
    await app.ghxOrgInvite('acme', 'friend', 'direct_member');
    ok(GH.state.orgInvites.some(i => i.body.invitee_id === 4242), 'member invited by username');
    await app.ghxOrgRemoveMember('acme', 'u2');
    ok(!GH.state.orgMembers.some(m => m.login === 'u2'), 'member removed');
    await app.ghxOpenOrg('acme', 'teams');
    ok(d.querySelector('[data-team="core"]'), 'teams listed (#482)');
    await app.ghxCreateTeam('acme', { name: 'Web Team', description: 'web', privacy: 'secret' });
    ok(GH.state.teams.some(t => t.slug === 'web-team' && t.privacy === 'secret'), 'team created');
    await app.ghxOpenTeam('acme', 'core');
    await app.ghxTeamAddMember('acme', 'core', 'u1');
    ok(GH.state.teamMembers.get('core').includes('u1'), 'team member added');
    await app.ghxOpenOrg('acme', 'billing');
    ok(/actions/.test(body().textContent) && /\$1\.20/.test(body().textContent) && /team/.test(body().textContent), 'billing usage aggregated per product (#485)');
    await app.ghxOpenOrg('acme', 'audit');
    ok(/Enterprise/.test(body().textContent) && d.querySelector('[data-event="PushEvent"]'), 'audit log falls back to org activity (#486)');
    app.ghView = null;
    await app.ghxLoad('org', 'collab');
    ok(d.querySelector('[data-collab="u1"]') && d.querySelector('[data-collab-role="u1"]'), 'repo collaborators with roles');
    await app.ghxAddCollaborator('newbie', 'triage');
    ok(GH.state.invitations.some(i => i.invitee.login === 'newbie' && i.permissions === 'triage'), 'collaborator invited with a role');
    await app.ghxSetCollaboratorRole('u1', 'maintain');
    ok(GH.state.collaborators.find(c => c.login === 'u1').role_name === 'maintain', 'collaborator role changed');
    await app.ghxLoad('org', 'audit');
    ok(d.querySelectorAll('[data-event]').length === 3, 'repo activity log');
    downloads.length = 0;
    const n = await app.ghxExportEvents();
    ok(n === 3 && downloads[0].name.endsWith('-activity.csv'), 'activity exported as CSV');

    // ------------------------------------------------------------------
    section('Release assets (#453) + hub integration');
    app.ghView = null;
    await app.switchGhTab('releases');
    await wait(10);
    ok(body().querySelector('[data-ghx-assets]'), 'releases tab gets an «Assets» entry');
    await app.ghxReleaseAssetsList();
    ok(d.querySelector('[data-asset="21"]') && /app\.zip/.test(body().textContent), 'release assets listed');
    const up = await app.ghxUploadAssets(11, [new w.Blob(['hello'], { type: 'text/plain' })].map(b => Object.assign(b, { name: 'notes.txt' })));
    ok(up && up.length === 1 && GH.state.uploads[0].name === 'notes.txt' && GH.log.some(l => l.host === 'uploads.github.com' && /name=notes\.txt/.test(l.query) && l.auth === 'Bearer ghp_test'), 'asset uploaded to uploads.github.com with the token');
    setConfirm(true);
    await app.ghxDeleteAsset(21, 'app.zip');
    ok(!GH.state.releases[0].assets.some(a => a.id === 21), 'asset deleted');
    app.ghView = null;
    await app.switchGhTab('prs');
    await app.openGitHubPro('analytics', 'traffic');
    await wait(20);
    ok(app.ghTab === 'analytics' && body().querySelector('[data-ghx-sec="traffic"].ghx-sec'), 'openGitHubPro opens a tab on a given section');
    await app.refreshGitHubHub();
    ok(body().querySelector('[data-ghx-sec="traffic"].ghx-sec'), 'refresh re-renders the current section');
    const pal = app.buildPaletteCommands().filter(c => c.section === 'GitHub Pro');
    ok(pal.length >= 18 && pal.every(c => typeof c.run === 'function'), `palette section (${pal.length})`);
    const all = app.buildPaletteCommands();
    ok(all.filter(c => /ثيم/.test(c.label)).length === 10 && all.filter(c => /تصدير المحادثة/.test(c.label)).length === 1, 'existing palette label counts unchanged');
    app.closeModals();
    w.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'k', altKey: true }));
    await wait(40);
    ok($('gh-hub-modal').classList.contains('active') && app.ghTab === 'search', 'Alt+K opens GitHub search');
    // Gist button on chat code blocks
    if (!('innerText' in w.HTMLElement.prototype)) Object.defineProperty(w.HTMLElement.prototype, 'innerText', { configurable: true, get() { return this.textContent; }, set(v) { this.textContent = v; } });
    const cont = $('chat-messages-container');
    cont.innerHTML = '<div class="markdown-body"><pre><code class="language-python">def hi():\n    return 1</code></pre></div>';
    app.enhanceRenderedCodeBlocks();
    const gb = cont.querySelector('[data-gist-btn]');
    ok(gb, 'chat code blocks get a «Gist» button (#479)');
    const before3 = GH.state.gists.length;
    gb.click();
    await wait(60);
    ok(GH.state.gists.length === before3 + 1 && GH.state.gists[0].files['hi.py'], 'code-block Gist button creates hi.py');
    ok(dialogs.length > 0, 'dialogs used for confirmations');
